function t(key) {
  return translations[currentLanguage][key] ?? translations.ca[key] ?? key;
}

function formatDate(value) {
  if (!value) return "";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return value;
  const locale = currentLanguage === "ca" ? "ca-ES" : currentLanguage === "es" ? "es-ES" : "en-GB";
  return new Intl.DateTimeFormat(locale, { day: "2-digit", month: "short", year: "numeric" }).format(date);
}

function isNowPost(post) {
  if (!post.published_at) return false;

  const publishedAt = new Date(post.published_at).getTime();
  if (Number.isNaN(publishedAt)) return false;

  const ageHours = (Date.now() - publishedAt) / (60 * 60 * 1000);
  if (ageHours < 0) return false;

  if (post.category === "alerts") return ageHours <= 168;
  if (post.category === "services") return ageHours <= 120;
  return ageHours <= 24;
}

function nowPriority(post) {
  const categoryPriority = {
    alerts: 0,
    services: 1,
    agenda: 2,
    news: 3,
    culture: 4,
    sports: 5,
    commerce: 6,
    social: 7
  };
  return categoryPriority[post.category] ?? 9;
}

function iconFor(category) {
  return {
    alerts: "🚨",
    services: "🛠️",
    agenda: "📅",
    culture: "🎭",
    sports: "🏅",
    commerce: "🏪",
    social: "📱",
    news: "📰"
  }[category] || "📰";
}

function applyTranslations() {
  document.documentElement.lang = currentLanguage;
  languageSelect.value = currentLanguage;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = t(element.dataset.i18nPlaceholder);
  });

  populateSourceSelect();
  updateSourceHealth();
  updateLastUpdated();
  renderFeed();
}

function formatStatusTemplate(key, values) {
  return Object.entries(values).reduce(
    (value, [name, replacement]) => value.replaceAll(`{${name}}`, String(replacement)),
    t(key)
  );
}

function updateSourceHealth() {
  if (!sourceHealthTitle || !sourceHealthBody || !sourceStatus.length) return;

  const total = sourceStatus.length;
  const ok = sourceStatus.filter((source) => source.ok).length;
  const healthy = ok === total;

  sourceHealthTitle.textContent = formatStatusTemplate(
    healthy ? "hero.statusHealthy" : "hero.statusPartial",
    { ok, total }
  );
  sourceHealthBody.textContent = t(
    healthy ? "hero.statusHealthyBody" : "hero.statusPartialBody"
  );
}

function updateLastUpdated() {
  if (usingDemoData) {
    lastUpdated.textContent = t("feed.demo");
    return;
  }
  if (!fetchedAt) {
    lastUpdated.textContent = t("feed.loading");
    return;
  }
  const date = new Date(fetchedAt);
  const locale = currentLanguage === "ca" ? "ca-ES" : currentLanguage === "es" ? "es-ES" : "en-GB";
  const formatted = new Intl.DateTimeFormat(locale, {
    day: "2-digit",
    month: "short",
    hour: "2-digit",
    minute: "2-digit"
  }).format(date);
  lastUpdated.textContent = `${t("feed.updated")}: ${formatted}`;
}

function populateSourceSelect() {
  const currentValue = currentSource;
  const uniqueSources = new Map(
    configuredSources
      .filter((source) => source && source.id && source.name)
      .map((source) => [source.id, { id: source.id, name: source.name }])
  );
  posts
    .filter((post) => post.source_id && post.source)
    .forEach((post) => uniqueSources.set(post.source_id, { id: post.source_id, name: post.source }));

  const options = [...uniqueSources.values()]
    .sort((a, b) => a.name.localeCompare(b.name, currentLanguage));

  sourceSelect.innerHTML = `<option value="all">${t("source.all")}</option>`
    + options.map((source) => `<option value="${escapeAttribute(source.id)}">${escapeHtml(source.name)}</option>`).join("");

  sourceSelect.value = options.some((source) => source.id === currentValue) ? currentValue : "all";
  currentSource = sourceSelect.value;
}


function renderFeed() {
  if (socialSources) {
    socialSources.hidden = currentCategory !== "social";
  }

  const normalizedSearch = currentSearch.trim().toLocaleLowerCase(currentLanguage);
  let visiblePosts = posts.filter((post) => {
    const categoryMatches = currentCategory === "all"
      || (currentCategory === "now"
        ? isNowPost(post)
        : currentCategory === "social"
          ? post.source_type === "social"
          : post.category === currentCategory);
    const sourceMatches = currentSource === "all" || post.source_id === currentSource;
    const relatedText = Array.isArray(post.related_sources) ? post.related_sources.map((item) => `${item.source || ""} ${item.title || ""}`).join(" ") : "";
    const haystack = `${post.title || ""} ${post.summary || ""} ${post.source || ""} ${relatedText}`.toLocaleLowerCase(currentLanguage);
    const searchMatches = !normalizedSearch || haystack.includes(normalizedSearch);
    return categoryMatches && sourceMatches && searchMatches;
  });

  if (currentCategory === "now") {
    visiblePosts = [...visiblePosts].sort((a, b) => {
      const dateDiff = new Date(b.published_at).getTime() - new Date(a.published_at).getTime();
      if (dateDiff !== 0) return dateDiff;
      return nowPriority(a) - nowPriority(b);
    });
  }

  if (!visiblePosts.length) {
    feed.innerHTML = `<div class="empty">${t("empty")}</div>`;
    return;
  }

  feed.innerHTML = visiblePosts.map((post) => {
    const categoryLabel = translations[currentLanguage].categories[post.category] || post.category;
    const safeUrl = post.url || "#";
    const officialPreview = renderOfficialLinkPreview(post);
    const socialEmbed = renderSocialEmbed(post);
    const socialLabel = post.source_type === "social" && post.platform
      ? `<span class="social-platform">${escapeHtml(post.platform)}</span>`
      : "";
    const relatedSources = Array.isArray(post.related_sources) ? post.related_sources : [];
    const relatedHtml = relatedSources.length
      ? `<div class="related-sources"><span>${t("card.related")}:</span>${relatedSources.map((item) => `<a href="${escapeAttribute(item.url || "#")}" target="_blank" rel="noopener noreferrer">${escapeHtml(item.source || "")}</a>`).join("")}</div>`
      : "";
    return `
      <article class="card">
        <div class="card-media" aria-hidden="true">${iconFor(post.category)}</div>
        <div class="card-body">
          <div class="meta">
            <span class="source-wrap">${post.source_type === "official" ? '<span class="official-dot" aria-hidden="true"></span>' : ""}<span class="source-name">${escapeHtml(post.source || "")}</span>${post.account ? `<span class="social-account">${escapeHtml(post.account)}</span>` : ""}${socialLabel}</span>
            <span>${formatDate(post.published_at)}</span>
          </div>
          <span class="badge">${escapeHtml(categoryLabel)}</span>
          <h3>${escapeHtml(post.title || "")}</h3>
          ${post.summary ? `<p>${escapeHtml(post.summary)}</p>` : ""}
          ${officialPreview}
          ${socialEmbed}
          ${relatedHtml}
          <div class="card-actions">
            ${post.source_type === "own" ? "" : `<a class="origin-link" href="${escapeAttribute(safeUrl)}" target="_blank" rel="noopener noreferrer">${t("card.original")} →</a>`}
            <button class="muted-button" type="button" data-share-id="${escapeAttribute(post.id || "")}">${t("card.share")}</button>
          </div>
        </div>
      </article>`;
  }).join("");

  document.querySelectorAll("[data-share-id]").forEach((button) => {
    button.addEventListener("click", () => sharePost(button.dataset.shareId));
  });

  ensureXWidgets();
  ensureInstagramWidgets();
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function escapeAttribute(value) {
  return escapeHtml(value);
}

function extractYouTubeId(url) {
  try {
    const parsed = new URL(url);
    if (parsed.hostname.includes("youtu.be")) return parsed.pathname.slice(1).split("/")[0];
    if (parsed.pathname.startsWith("/shorts/")) return parsed.pathname.split("/")[2];
    if (parsed.pathname.startsWith("/embed/")) return parsed.pathname.split("/")[2];
    return parsed.searchParams.get("v") || "";
  } catch (_) {
    return "";
  }
}

function extractTikTokId(url) {
  const match = String(url || "").match(/\/video\/(\d+)/);
  return match ? match[1] : "";
}

function renderOfficialLinkPreview(post) {
  if (post.embed_type !== "official_oembed" || !post.embed_url || !post.url) return "";
  try {
    const original = new URL(post.url);
    const embed = new URL(post.embed_url);
    const originalHost = original.hostname.replace(/^www\./, "");
    const embedHost = embed.hostname.replace(/^www\./, "");
    const expectedPath = `${original.pathname.replace(/\/$/, "")}/embed/`;
    if (original.protocol !== "https:" || embed.protocol !== "https:"
        || originalHost !== embedHost || embed.pathname !== expectedPath) return "";
    return `
      <div class="social-embed source-link-preview">
        <iframe
          src="${escapeAttribute(embed.href)}"
          title="${escapeAttribute(`Vista previa de ${post.source || "la fuente original"}`)}"
          loading="lazy"
          sandbox="allow-scripts allow-same-origin allow-popups"
          referrerpolicy="strict-origin-when-cross-origin"></iframe>
      </div>`;
  } catch (_) {
    return "";
  }
}

function renderSocialEmbed(post) {
  if (post.source_type === "own" && post.media_type === "image" && post.media_url) {
    return `
      <div class="social-embed social-embed-image own-post-image">
        <img src="${escapeAttribute(post.media_url)}" alt="" loading="lazy" />
      </div>`;
  }

  if (post.source_type !== "social" || !post.url) return "";

  const platform = String(post.platform || "").toLowerCase();

  if (platform === "x" || platform === "twitter") {
    return `
      <div class="social-embed social-embed-x" data-x-embed>
        <blockquote class="twitter-tweet" data-dnt="true">
          <a href="${escapeAttribute(post.url)}"></a>
        </blockquote>
      </div>`;
  }

  if (platform === "instagram") {
    return `
      <div class="social-embed social-embed-instagram">
        <blockquote
          class="instagram-media"
          data-instgrm-permalink="${escapeAttribute(post.url)}"
          data-instgrm-version="14"></blockquote>
      </div>`;
  }

  if (platform === "tiktok") {
    const id = extractTikTokId(post.url);
    if (!id) return "";
    return `
      <div class="social-embed social-embed-video">
        <iframe
          src="https://www.tiktok.com/player/v1/${escapeAttribute(id)}?autoplay=0&description=1"
          title="${escapeAttribute(post.title || "TikTok")}"
          loading="lazy"
          allow="fullscreen"
          allowfullscreen></iframe>
      </div>`;
  }

  if (platform === "youtube") {
    const id = extractYouTubeId(post.url);
    if (!id) return "";
    return `
      <div class="social-embed social-embed-video">
        <iframe
          src="https://www.youtube-nocookie.com/embed/${escapeAttribute(id)}"
          title="${escapeAttribute(post.title || "YouTube")}"
          loading="lazy"
          allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share"
          allowfullscreen></iframe>
      </div>`;
  }

  if (post.media_type === "image" && post.image_allowed && post.media_url) {
    return `
      <div class="social-embed social-embed-image">
        <img src="${escapeAttribute(post.media_url)}" alt="" loading="lazy" referrerpolicy="no-referrer" />
      </div>`;
  }

  return "";
}

function ensureInstagramWidgets() {
  if (!document.querySelector(".instagram-media")) return;

  if (window.instgrm?.Embeds) {
    window.instgrm.Embeds.process();
    return;
  }

  if (document.querySelector('script[data-soller-instagram-embed]')) return;

  const script = document.createElement("script");
  script.src = "https://www.instagram.com/embed.js";
  script.async = true;
  script.dataset.sollerInstagramEmbed = "true";
  script.addEventListener("load", () => window.instgrm?.Embeds?.process());
  document.body.appendChild(script);
}

function ensureXWidgets() {
  if (!document.querySelector("[data-x-embed], .twitter-timeline")) return;

  if (window.twttr?.widgets) {
    window.twttr.widgets.load();
    return;
  }

  if (document.querySelector('script[data-soller-x-widgets]')) return;

  const script = document.createElement("script");
  script.src = "https://platform.twitter.com/widgets.js";
  script.async = true;
  script.charset = "utf-8";
  script.dataset.sollerXWidgets = "true";
  document.body.appendChild(script);
}

async function sharePost(postId) {
  const post = posts.find((item) => item.id === postId);
  if (!post) return;
  const shareData = { title: post.title, text: post.summary, url: post.url || window.location.href };

  if (navigator.share) {
    try { await navigator.share(shareData); } catch (_) {}
  } else if (navigator.clipboard) {
    await navigator.clipboard.writeText(`${post.title}\n${post.url || window.location.href}`);
  }
}

function applyPostsPayload(payload) {
  if (!payload || !Array.isArray(payload.posts)) {
    throw new Error("Invalid posts payload");
  }
  posts = payload.posts;
  fetchedAt = payload.fetched_at || null;
  sourceStatus = Array.isArray(payload.source_status) ? payload.source_status : [];
  usingDemoData = false;
}

async function loadConfiguredSources() {
  try {
    const response = await fetch(`sources.json?v=${Date.now()}`, { cache: "no-store" });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const payload = await response.json();
    configuredSources = Array.isArray(payload.sources) ? payload.sources : [];
  } catch (error) {
    console.warn("No s'han pogut carregar les fonts configurades", error);
    configuredSources = [];
  }
}

async function loadPosts() {
  const embeddedPayload = window.SOLLER_ARA_DATA;

  if (window.location.protocol === "file:" && embeddedPayload) {
    try {
      applyPostsPayload(embeddedPayload);
      populateSourceSelect();
      updateLastUpdated();
      renderFeed();
      return;
    } catch (error) {
      console.warn("No s'han pogut carregar les dades locals", error);
    }
  }

  try {
    const response = await fetch(`data/posts.json?v=${Date.now()}`, { cache: "no-store" });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const payload = await response.json();
    applyPostsPayload(payload);
  } catch (error) {
    console.warn("No s'ha pogut carregar data/posts.json", error);

    if (embeddedPayload) {
      try {
        applyPostsPayload(embeddedPayload);
      } catch (_) {
        posts = demoPosts;
        fetchedAt = null;
        usingDemoData = true;
      }
    } else {
      posts = demoPosts;
      fetchedAt = null;
      usingDemoData = true;
    }
  }

  await loadConfiguredSources();
  populateSourceSelect();
  updateSourceHealth();
  updateLastUpdated();
  renderFeed();
}

